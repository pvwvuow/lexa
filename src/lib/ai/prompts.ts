export function lessonContextBlock(ctx?: {
  courseTitle?: string; chapterTitle?: string; lessonTitle?: string; seenSections?: string[]; extra?: string;
  lawRegistry?: string[];
}): string {
  if (!ctx || (!ctx.lessonTitle && !ctx.extra && !ctx.lawRegistry?.length)) return '';
  const parts = [
    ctx.courseTitle && `درس: ${ctx.courseTitle}`,
    ctx.chapterTitle && `فصل: ${ctx.chapterTitle}`,
    ctx.lessonTitle && `جلسهٔ جاری: ${ctx.lessonTitle}`,
    ctx.seenSections?.length && `بخش‌هایی که دانشجو دیده: ${ctx.seenSections.join('، ')}`,
    ctx.lawRegistry?.length && `فهرست مواد قانونی معتبر همین جلسه (تنها شماره‌های مجاز برای ارجاع شماره‌ای):
${ctx.lawRegistry.map((l) => `- ${l}`).join('\n')}`,
    ctx.extra && `محتوای جلسه (منبع اصلی پاسخ تو — خارج از این متن دربارهٔ جزئیات جلسه اطلاعات نداری):
"""${ctx.extra.slice(0, 4500)}"""`,
  ].filter(Boolean);
  return `\n\nزمینهٔ جلسه:\n${parts.join('\n\n')}`;
}
