async function main() {
  const t = await db.user.findUnique({ where: { username: "mohamadsoleymani" } });
  if (!t) throw new Error("teacher mohamadsoleymani پیدا نشد");

  // ── مطلب نمایشی ──
  const existingPost = await db.post.findFirst({
    where: { authorId: t.id, title: { contains: "بیع" } },
    select: { id: true },
  });
  const post = existingPost
    ? await db.post.update({ where: { id: existingPost.id }, data: { blocks: POST_BLOCKS } })
    : await db.post.create({
        data: {
          authorId: t.id,
          title: "حقوق قراردادها در یک ساعت: عمق واژهٔ «بیع»",
          summary:
            "از مادهٔ ۳۳۸ تا خیارات — مرور فشرده اما عمیق عقد بیع همراه با ریزه‌کاری‌های آزمونی، مثال از پرونده‌های واقعی و جدول مقایسه با اجاره.",
          tags: "بیع,قراردادها,قانون مدنی,آزمون وکالت",
          blocks: POST_BLOCKS,
        },
      });
  console.log("post:", post.id);

  // ── دورهٔ آنلاین نمایشی ──
  const existingCourse = await db.teacherCourse.findFirst({
    where: { teacherId: t.id, title: { contains: "بیع" } },
    select: { id: true },
  });
  const course = existingCourse
    ? await db.teacherCourse.update({
        where: { id: existingCourse.id },
        data: { chaptersJson: JSON.stringify(COURSE_CHAPTERS), publishedAt: new Date() },
      })
    : await db.teacherCourse.create({
        data: {
          teacherId: t.id,
          title: "دورهٔ فشردهٔ عقد بیع",
          tagline: "صفر تا صد بیع برای آزمون و قراردادنگاری",
          description:
            "دو فصل کاربردی: پایه‌های انعقاد و اثر انتقال، سپس تمام خیارات با مثال‌های دفاتر امروز. همراه جدول‌های مقایسه و پرسش‌های تأملی.",
          chaptersJson: JSON.stringify(COURSE_CHAPTERS),
          publishedAt: new Date(),
        },
      });
  console.log("course:", course.id);

  // ── یک نظر نمونه از دانشجویی موجود (اگر هست) ──
  const student = await db.user.findFirst({
    where: { role: "user" },
    orderBy: { createdAt: "asc" },
    select: { id: true },
  });
  if (student && !(await db.comment.findFirst({ where: { postId: post.id } }))) {
    await db.comment.create({
      data: {
        postId: post.id,
        userId: student.id,
        text: "ممنون استاد! بخش خیارات و جدول مقایسه واقعاً فصل مرور آزمونم رو جا انداخت. از دوستام پرسیدم همشون همین مطلب رو لازم داشتن 🌸",
      },
    });
    console.log("comment added by student:", student.id);
  }

  console.log("DONE");
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => db.$disconnect());
